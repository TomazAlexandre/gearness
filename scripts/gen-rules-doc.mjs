// Regenerates docs/rules.md from the rule registry so docs never drift from code.
import { writeFileSync } from "node:fs";
import { RULES } from "../dist/rules.js";

const pillars = ["context", "commands", "tooling", "safety", "feedback"];
const total = RULES.reduce((n, r) => n + r.weight, 0);
let md = `# Rules\n\n<!-- generated by scripts/gen-rules-doc.mjs - run \`npm run docs:rules\` -->\n\n`;
md += `Each rule belongs to a pillar and is worth points in \`gearness doctor\` (total ${total}, normalized to 100). `;
md += "A rule with no findings earns full points; one whose worst finding is `info` earns 60%, `warn` 30%, `error` 0%, unless the rule defines proportional credit. ";
md += "Disable a rule with `rules.disable` in harness.yaml.\n";
for (const p of pillars) {
  md += `\n## ${p}\n\n| Rule | Severity | Points | What it checks |\n|---|---|---|---|\n`;
  for (const r of RULES.filter((r) => r.pillar === p)) md += `| \`${r.id}\` | ${r.severity} | ${r.weight} | ${r.description} |\n`;
}
writeFileSync(new URL("../docs/rules.md", import.meta.url), md);
console.log(`docs/rules.md: ${RULES.length} rules`);
