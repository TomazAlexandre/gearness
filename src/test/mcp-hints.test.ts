import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { describe, it } from "node:test";
import { handle, TOOLS } from "../mcp.js";
import { tmpRepo } from "./helpers.js";

const BARE = "version: 1\nproject:\n  name: p\nagents: []\ncommands:\n  test: npm test\n";
const repo = () => tmpRepo({ "harness.yaml": BARE, "AGENTS.md": "# p\n\nRun `npm test`.\n", "src/a.ts": 'import "./b";\n', "src/b.ts": "export {};\n" });

/** Hash of every file in the repository: any write, rename or delete changes it. */
function snapshot(dir: string): string {
  const h = crypto.createHash("sha256");
  const walk = (rel: string) => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(r);
      else h.update(`${r}:${fs.readFileSync(path.join(dir, r), "utf8")}\n`);
    }
  };
  walk("");
  return h.digest("hex");
}

const call = async (dir: string, name: string, args: Record<string, unknown> = {}) =>
  (await handle({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: args } }, dir)) as { result: { isError?: boolean } };

const ARGS: Record<string, Record<string, unknown>> = {
  harness_overview: {},
  harness_rules_for_path: { path: "src" },
  harness_verify_commands: {},
  harness_check_files: { files: ["src/a.ts"] },
  harness_can_import: { file: "src/a.ts", import: "./b" },
};

describe("MCP tool hints", () => {
  it("every tool declares all four hints as explicit booleans", () => {
    for (const t of TOOLS) {
      for (const k of ["readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint"]) {
        assert.equal(typeof t.annotations?.[k], "boolean", `${t.name}.${k}`);
      }
    }
  });

  it("no tool reaches outside the repository (open world is false everywhere)", () => {
    assert.ok(TOOLS.every((t) => t.annotations?.openWorldHint === false));
  });

  it("exactly one tool writes, and it is the lesson recorder", () => {
    assert.deepEqual(TOOLS.filter((t) => t.annotations?.readOnlyHint === false).map((t) => t.name), ["harness_record_lesson"]);
  });

  it("tools declared read-only change nothing on disk", async () => {
    const dir = repo();
    for (const t of TOOLS.filter((x) => x.annotations?.readOnlyHint === true)) {
      const args = ARGS[t.name];
      assert.ok(args, `add arguments for ${t.name} to this test`);
      const before = snapshot(dir);
      const r = await call(dir, t.name, args);
      assert.ok(!r.result.isError, `${t.name} failed`);
      assert.equal(snapshot(dir), before, `${t.name} declares readOnlyHint but modified the repository`);
      await call(dir, t.name, args); // idempotent: a second call is just as harmless
      assert.equal(snapshot(dir), before);
    }
  });

  it("the lesson recorder is append-only and not idempotent, as declared", async () => {
    const dir = repo();
    const hints = TOOLS.find((t) => t.name === "harness_record_lesson")!.annotations!;
    assert.deepEqual([hints.destructiveHint, hints.idempotentHint], [false, false]);
    const args = { failure: "edited generated code", fix: "doc", rule: "Never edit src/generated by hand." };
    assert.ok(!(await call(dir, "harness_record_lesson", args)).result.isError);
    const first = fs.readFileSync(path.join(dir, ".harness/ratchet.yaml"), "utf8");
    assert.ok(!(await call(dir, "harness_record_lesson", { failure: "second mistake", fix: "doc", rule: "Always use the injected clock." })).result.isError);
    const second = fs.readFileSync(path.join(dir, ".harness/ratchet.yaml"), "utf8");
    assert.ok(second.includes("edited generated code"), "the earlier entry is still there: nothing was destroyed");
    assert.ok(second.includes("second mistake") && second.length > first.length, "each call adds an entry");
    const entry = fs.readFileSync(path.join(dir, "AGENTS.md"), "utf8");
    assert.ok(entry.includes("Never edit src/generated by hand") && entry.includes("Always use the injected clock"), "both rules were appended");
    assert.ok(entry.startsWith("# p\n\nRun `npm test`."), "the original content is untouched");
  });
});
